#!/usr/bin/env python3
"""Регрессионные проверки защиты от чужих документов (import-kb.py).

Смысл защиты: печатная версия статьи на 1gb.uz не всегда начинается с её
заголовка, и по первому входу нельзя отличить «свой» документ от «чужого».
Ошибки в этом месте стоили 455 битых статей, поэтому каждое сомнительное
решение закреплено здесь.

Запуск:  python3 tools/export-mcfr/test-import-guard.py
"""

import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    path = os.path.join(HERE, "import-kb.py")
    # import-kb.py импортируется как модуль, поэтому рядом с ним копится
    # __pycache__/import-kb.*.pyc. Если файл правили, а .pyc остался старый
    # (совпали размер и mtime), проверки молча идут по прежнему коду и
    # «проходят» или падают в зависимости от того, что было до правки.
    # Поэтому кэш сбрасываем насильно.
    cache = os.path.join(HERE, "__pycache__")
    if os.path.isdir(cache):
        for name in os.listdir(cache):
            if name.startswith("import-kb."):
                os.remove(os.path.join(cache, name))
    sys.dont_write_bytecode = True
    importlib.invalidate_caches()
    spec = importlib.util.spec_from_file_location("import_kb", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


kb = load()
FAILS = []


def check(name, got, want):
    ok = got == want
    print(("  ok   " if ok else "  FAIL ") + name)
    if not ok:
        print(f"         ожидалось: {want!r}\n         получено : {got!r}")
        FAILS.append(name)


def doc(inner, body=""):
    """Синтетический печатный файл: заголовок + текст.

    file_own_title() берёт первую строку длиннее 20 символов после
    нормализации, поэтому в фикстурах нужны полные заголовки, а не огрызки.
    """
    return (
        '<html><head><meta name="description" content="Print 90"></head><body>'
        f"<h1>{inner}</h1><p>{body}</p></body></html>"
    ).encode("utf-8")


print("заголовок и содержимое расходятся — документ чужой")
check(
    "свой документ: заголовок совпал",
    kb.title_conflicts(
        {"data": doc("Как уплачивать НДС при экспорте и импорте услуг", "Место реализации услуг")},
        "Как уплачивать НДС при экспорте и импорте услуг",
        "Место реализации услуг определяет объект налогообложения",
    ),
    "",
)
check(
    "чужой документ отсекается",
    kb.title_conflicts({"data": doc("Руководитель принимает решение об инвентаризации", "Перечень активов")},
                       "Кто платит НДС в 2026 году и как перейти на ставку 6 процентов",
                       "Порог выручки вырос до 12 000 базовых единиц"),
    "заголовок в файле: Руководитель принимает решение об инвентаризации",
)
check(
    "чужой документ под видом НПА отсекается по тексту",
    kb.title_conflicts(
        {"data": doc("Закон от 13.04.2016 № ЗРУ-404", "Трудовой договор")},
        "Налоговый кодекс Республики Узбекистан", "Раздел 1. Общие положения",
    ),
    "текст не подтверждает заголовок «Налоговый кодекс Республики Узбекистан»",
)

print("\nлид вместо заголовка — материал верный, отсекать нельзя")
# Регрессия №1: на сайте «Когда понадобит**ьс**я» (с мягким знаком), а проверка
# искала «понадобится». Пять табелей выпали из корпуса как «чужие».
check(
    "лид «Когда понадобиться» не считается чужим документом",
    kb.title_conflicts(
        {"data": doc("Когда понадобиться: при подготовке табеля учета рабочего времени")},
        "Табель учета рабочего времени за август 2026 года",
        "Форма табеля за август 2026 года приведена ниже",
    ),
    "",
)
# Регрессия №2: у подборок-заставок заголовок стоит в обложке-таблице, которую
# html_to_md выбрасывает. Сверять надо по сырому файлу, а не по конвертации.
check(
    "подборка «Главное в августе»: заголовок в обложке, конвертер его выкинул",
    kb.title_conflicts(
        {"data": doc("Главное в августе", "Ежемесячный обзор Системы Главбух")},
        "Главное в августе",
        "## Читайте в первую очередь\n| ![](https://1gb.uz/system/content/image/297/1/1/) |  |",
    ),
    "",
)
check(
    "материал под paywall не отсекается",
    kb.title_conflicts({"data": doc("Приложение в платном доступе")},
                       "Руководство", "Приложение в платном доступе"),
    "",
)

print("\n_title_appears_in_body смотрит и в сырой файл")
raw = doc("Главное в сентябре", "Ежемесячный обзор")
check(
    "пустой body, но заголовок есть в сыром файле",
    kb._title_appears_in_body("Главное в сентябре", "", raw),
    True,
)
check(
    "заголовка нет нигде",
    kb._title_appears_in_body("Как уплачивать НДС", "Совсем другой текст", raw),
    False,
)

print()
if FAILS:
    print(f"ПРОВАЛЕНО проверок: {len(FAILS)}")
    for f in FAILS:
        print("  - " + f)
    sys.exit(1)
print("Все проверки пройдены.")
