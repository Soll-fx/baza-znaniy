/**
 * Классификация изображений: несут ли они смысловую нагрузку.
 *
 * Источник 1gb.uz не отдаёт alt почти ни для одной картинки, поэтому часть
 * файлов приходится помечать как декоративные. Для них пустой alt — не ошибка,
 * а корректная разметка по WCAG: скринридер пропускает картинку, не зачитывая
 * «изображение». Требовать alt у баннера «Как задать вопрос?» значит заставить
 * скринридер читать бесполезный текст.
 *
 * Правила намеренно опираются на объективные признаки (контекст в разметке и
 * размеры файла), а не на догадки о содержимом.
 */

/** Признаки, по которым решается, декоративна ли картинка. */
export interface ImageSignals {
  /** Картинка обёрнута в ссылку — обычно баннер или кнопка. */
  inLink: boolean;
  /** Картинка стоит в ячейке таблицы — обычно логотип рядом с текстом. */
  inTable: boolean;
  width: number | null;
  height: number | null;
  /** Роль из frontmatter: вложениям alt не нужен по определению. */
  role?: string;
}

/**
 * Высота, ниже которой картинка считается иконкой или горизонтальной полоской
 * ( баннеры 1gb.uz имеют высоту 47-54 px, иконки — 80 px).
 */
export const THIN_IMAGE_HEIGHT = 110;

/**
 * Логотип в таблице — обычно квадратный и небольшой, а подпись рядом с ним
 * уже несёт текст, который и должен читать скринридер.
 */
export const LOGO_MAX_SIDE = 320;

export function isDecorativeImage(s: ImageSignals): boolean {
  if (s.role === 'attachment') return true;
  if (s.inLink) return true;
  if (s.height !== null && s.height <= THIN_IMAGE_HEIGHT) return true;
  if (s.inTable && (s.width ?? 0) <= LOGO_MAX_SIDE && (s.height ?? 0) <= LOGO_MAX_SIDE) {
    return true;
  }
  return false;
}
